    def follow_path(self, result, headless = False):
        """Helper function to follow a path generated by the planner"""
        # number of waypoints in the path
        n_step = result["position"].shape[0]
        # this makes sure the robot stays neutrally boyant instead of sagging
        # under gravity
        print(f"follow_path中得到的plan给出的总时间步数:{n_step} 总用时：{result['duration']}")

        for i in range(n_step):
            qf = self.robot.compute_passive_force(
                gravity=True, coriolis_and_centrifugal=True
            )
            self.robot.set_qf(qf)
            # set the joint positions and velocities for move group joints only.
            # The others are not the responsibility of the planner
            for j in range(len(self.planner.move_group_joint_indices)):
                self.active_joints[j].set_drive_target(result["position"][i][j])
                self.active_joints[j].set_drive_velocity_target(
                    result["velocity"][i][j]
                )
            # simulation step
            self.scene.step()
            # render every 4 simulation steps to make it faster 渲染环境
            if i % 4 == 0 and not headless:
                self.scene.update_render()
                self.viewer.render()
        
        cur_pose = self.robot.find_link_by_name('gripper_base').pose.raw_pose[0].tolist()
        print("运动结束，已到达点: [" + ", ".join(f"{x:.2f}" for x in cur_pose) + "]\n")

