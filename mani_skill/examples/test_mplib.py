    def move_to_pose_with_retry(self, pose, with_screw=True, max_retries=5, headless=False):
        """
        尝试移动到目标位姿，失败时在邻域内随机扰动重试
        """
        # 初始尝试
        result = self.move_to_pose(pose, with_screw)
        if result == 0:
            return 0  # 初始尝试成功
        
        # 重试机制
        original_pose = np.array(pose)  # 转换为numpy数组便于处理
        pos = original_pose[:3]         # 位置向量 [x, y, z]
        quat = original_pose[3:]        # 四元数 [qx, qy, qz, qw]

        for attempt in range(max_retries):
            print(f"\n第 {attempt+1} 次重试，原始目标: {[f'{x:.3f}' for x in original_pose]}")
            
            # ===== 位置扰动 =====
            new_pos = pos + np.random.uniform(-0.01, 0.01, size=3)
            
            # ===== 基于四元数的姿态扰动=====
            # 创建原始旋转对象
            orig_rot = Rotation.from_quat(quat)
            
            # 生成随机扰动旋转（小角度）
            random_axis = np.random.randn(3)  # 随机轴
            random_axis /= np.linalg.norm(random_axis)  # 归一化
            random_angle = np.random.uniform(-0.5, 0.5)  # 随机角度（度）
            
            # 创建扰动旋转对象
            perturb_rot = Rotation.from_rotvec(random_angle * np.pi/180 * random_axis)
            
            # 应用扰动：新旋转 = 扰动旋转 × 原始旋转
            new_rot = perturb_rot * orig_rot
            new_quat = new_rot.as_quat()  # [qx, qy, qz, qw]
            
            # 组合新位姿
            new_pose = np.concatenate([new_pos, new_quat]).tolist()
            
            # 尝试新位姿
            result = self.move_to_pose(new_pose, with_screw)
            if result == 0:
                return 0  # 重试成功
        
        # 所有重试均失败
        print(f"\n⚠️ 警告: 经过 {max_retries} 次重试仍失败")
        return result


